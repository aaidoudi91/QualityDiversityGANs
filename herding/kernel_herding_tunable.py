"""Tunable Kernel Herding for A2 MNIST: original Eq. 8 plus ablation controls.

Run from the ROOT of the group's cloned GitHub repository. Does not change
model.py, train.py, generate.py or checkpoints/G.pth. No VAE required.

This is Eq. 8 over a finite pool of images generated by the fixed professor
Generator, with an empirical MNIST *training* reference distribution and an
RBF kernel on raw pixels by default; optional 2x2 pooled-pixel features.

Attraction weight != 1 is an EXPERIMENTAL VARIANT, not original Eq. 8.

Citation: https://proceedings.mlr.press/r8/chen10a.html
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
from PIL import Image
import torch
import torch.nn.functional as F
from torchvision.datasets import MNIST

from gan.model import Generator


def select_device(requested: str) -> torch.device:
    if requested != "auto":
        device = torch.device(requested)
        if device.type == "cuda" and not torch.cuda.is_available():
            raise RuntimeError("CUDA requested but no CUDA GPU found")
        return device
    if torch.cuda.is_available():
        return torch.device("cuda")
    if hasattr(torch.backends, "mps") and torch.backends.mps.is_available():
        return torch.device("mps")
    return torch.device("cpu")


def kernel_rbf(a: torch.Tensor, b: torch.Tensor, sigma: float) -> torch.Tensor:
    """RBF kernel matrix; a=(A,D), b=(B,D)."""
    if sigma <= 0:
        raise ValueError("sigma must be positive")
    a2 = a.square().sum(dim=1, keepdim=True)
    b2 = b.square().sum(dim=1).unsqueeze(0)
    d2 = (a2 + b2 - 2.0 * a @ b.T).clamp_min_(0.0)
    return (-d2 / (2.0 * sigma**2)).exp_()


def estimate_sigma(x: torch.Tensor, seed: int) -> float:
    """Median pairwise Euclidean distance, an implementation choice (not in Eq. 8)."""
    rng = np.random.default_rng(seed)
    indices = rng.choice(len(x), size=min(len(x), 384), replace=False)
    sample = x[torch.tensor(indices, device=x.device)]
    distances = torch.pdist(sample, p=2)
    positive = distances[distances > 1e-7]
    if len(positive) == 0:
        raise ValueError("All sampled images identical; specify --sigma")
    return float(positive.median().item())


@torch.no_grad()
def kernel_target_mean(candidates: torch.Tensor, reference: torch.Tensor,
                       sigma: float, block: int = 256) -> torch.Tensor:
    """m(x) = mean_{r in MNIST train} k(x, r); no MNIST test images."""
    output = torch.empty(len(candidates), dtype=torch.float32, device=candidates.device)
    for start in range(0, len(candidates), block):
        subset = candidates[start:start + block]
        score = torch.zeros(len(subset), device=candidates.device)
        for j in range(0, len(reference), block):
            score += kernel_rbf(subset, reference[j:j + block], sigma).sum(dim=1)
        output[start:start + len(subset)] = score / len(reference)
    return output


@torch.no_grad()
def greedy_kernel_herding(candidates: torch.Tensor, reference: torch.Tensor,
                          n_select: int, sigma: float | None = None,
                          *, unique: bool = False, seed: int = 42,
                          attraction_weight: float = 1.0, sigma_scale: float = 1.0,
                          progress: bool = True) -> tuple[np.ndarray, float]:
    """Finite-candidate implementation of Eq. 8.

    For t already selected points, choose argmax_x [m(x) - sum_j k(x,x_j)/(t+1)].
    Default allows repeats, as does the paper's recurrence.
    unique=True is a PRACTICAL VARIANT, not literally the original algorithm.
    """
    if attraction_weight <= 0 or sigma_scale <= 0:
        raise ValueError("attraction_weight and sigma_scale must be positive")
    if n_select < 1 or len(reference) < 2 or len(candidates) < 2:
        raise ValueError("Need positive n_select and at least two real/candidate images")
    if candidates.shape[1] != reference.shape[1]:
        raise ValueError("Candidate and reference dimensions differ")
    if unique and n_select > len(candidates):
        raise ValueError("--unique requires n_candidates >= n_samples")
    if sigma is None:
        sigma = estimate_sigma(torch.cat((candidates[:512], reference[:512])), seed)
    sigma = sigma * sigma_scale

    m = kernel_target_mean(candidates, reference, sigma)
    norms2 = candidates.square().sum(dim=1)
    used = torch.zeros(len(candidates), dtype=torch.bool, device=candidates.device)
    penalty = torch.zeros(len(candidates), dtype=torch.float32, device=candidates.device)
    ids = np.empty(n_select, dtype=np.int64)

    for t in range(n_select):
        # Chen et al. Eq. 8, with w_0 = target mean embedding.
        score = attraction_weight * m - penalty / (t + 1)
        if unique:
            score = score.masked_fill(used, float("-inf"))
        idx = int(score.argmax().item())
        ids[t] = idx
        if unique:
            used[idx] = True
        d2 = (norms2 + norms2[idx] - 2.0 * candidates @ candidates[idx]).clamp_min_(0)
        penalty.add_((-d2 / (2.0 * sigma**2)).exp_())
        if progress and (t + 1) % max(1, n_select // 5) == 0:
            print(f"Herding : {t + 1}/{n_select}", flush=True)
    return ids, sigma


@torch.no_grad()
def generate_candidates(path: Path, n: int, batch_size: int, device: torch.device,
                        seed: int) -> torch.Tensor:
    G = Generator(g_output_dim=784).to(device)
    state = torch.load(path, map_location=device, weights_only=True)
    if isinstance(state, dict) and "state_dict" in state:
        state = state["state_dict"]
    state = {k.removeprefix("module."): v for k, v in state.items()}
    G.load_state_dict(state, strict=True)
    G.eval()
    # A locally seeded CPU RNG guarantees the same candidate pool for --method
    # random and herding, regardless of how the method is selected.
    rng = torch.Generator(device="cpu").manual_seed(seed)
    outputs = []
    for start in range(0, n, batch_size):
        size = min(batch_size, n - start)
        z = torch.randn(size, 100, generator=rng).to(device)
        # The professor's generate.py calls torchvision.save_image on the raw
        # tanh output: this CLAMPS [-1,1] to [0,1] (does not rescale).
        outputs.append(G(z).clamp(0, 1).cpu())
    return torch.cat(outputs, dim=0)


def map_features(images: torch.Tensor, mode: str) -> torch.Tensor:
    """Feature selection changes the kernel, not the generator or saved PNG pixels."""
    if mode == "pixels":
        return images
    if mode == "pool2":
        return F.avg_pool2d(images.reshape(-1, 1, 28, 28), 2).flatten(1)
    raise ValueError(mode)


def main() -> None:
    ap = argparse.ArgumentParser(description="A2: Chen et al. 2010 Kernel Herding on MNIST GAN outputs")
    ap.add_argument("--method", choices=("herding", "random"), default="herding")
    ap.add_argument("--checkpoint", default="checkpoints/G.pth")
    ap.add_argument("--data_root", default="data")
    ap.add_argument("--output_dir", default="samples_kh_demo")
    ap.add_argument("--n_candidates", type=int, default=400)
    ap.add_argument("--n_samples", type=int, default=80)
    ap.add_argument("--n_reference", type=int, default=128)
    ap.add_argument("--batch_size", type=int, default=256)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--sigma", type=float, default=None)
    ap.add_argument("--sigma_scale", type=float, default=1.0,
                    help="Multiplier for automatic sigma (or explicit --sigma)")
    ap.add_argument("--attraction_weight", type=float, default=1.0,
                    help="1.0 = canonical equation; >1 gives more weight to real-data attraction (VARIANT)")
    ap.add_argument("--features", choices=("pixels", "pool2"), default="pixels",
                    help="pixels = original tested kernel; pool2 = RBF on 14x14 average-pooled pixels")
    ap.add_argument("--device", choices=("auto", "cpu", "cuda"), default="auto")
    ap.add_argument("--unique", action="store_true", help="no duplicate candidate indices (variant)")
    args = ap.parse_args()

    if args.sigma_scale <= 0 or args.attraction_weight <= 0:
        ap.error("--sigma_scale and --attraction_weight must be positive")
    if min(args.n_candidates, args.n_samples, args.n_reference, args.batch_size) <= 0:
        ap.error("counts and batch_size must be positive")
    if args.n_samples > args.n_candidates and (args.unique or args.method == "random"):
        ap.error("with --unique or --method random, require n_candidates >= n_samples")
    if not Path(args.checkpoint).is_file():
        ap.error(f"checkpoint not found: {args.checkpoint}")

    device = select_device(args.device)
    print(f"Device: {device}; checkpoint: {args.checkpoint}", flush=True)
    candidates_cpu = generate_candidates(Path(args.checkpoint), args.n_candidates,
                                         args.batch_size, device, args.seed)
    print(f"Generated {len(candidates_cpu)} candidates", flush=True)
    sigma = None
    if args.method == "herding":
        # torchvision downloads MNIST with the SAME mechanism as the professor.
        train = MNIST(args.data_root, train=True, download=True)
        rng = np.random.default_rng(args.seed + 1000)
        ref_ids = rng.choice(len(train), size=min(args.n_reference, len(train)), replace=False)
        ref_cpu = train.data[ref_ids].reshape(-1, 784).float().div(255)
        candidate_features = map_features(candidates_cpu, args.features)
        reference_features = map_features(ref_cpu, args.features)
        ids, sigma = greedy_kernel_herding(
            candidate_features.to(device), reference_features.to(device), args.n_samples,
            sigma=args.sigma, unique=args.unique, seed=args.seed,
            attraction_weight=args.attraction_weight, sigma_scale=args.sigma_scale
        )
    else:
        ids = np.random.default_rng(args.seed + 2000).choice(
            args.n_candidates, size=args.n_samples, replace=False
        )

    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    # Separate output folders let us compare without changing the professor's samples/.
    for old in out_dir.glob("*.png"):
        old.unlink()
    images = candidates_cpu[torch.as_tensor(ids)].reshape(-1, 28, 28)
    for i, img in enumerate(images):
        png = (img * 255).round().to(torch.uint8).numpy()
        Image.fromarray(png, mode="L").save(out_dir / f"{i}.png")
    manifest = dict(method=args.method, checkpoint=args.checkpoint,
                    seed=args.seed, n_candidates=args.n_candidates,
                    n_samples=args.n_samples, n_reference=args.n_reference,
                    unique=args.unique, sigma=sigma,
                    attraction_weight=args.attraction_weight,
                    sigma_scale=args.sigma_scale, features=args.features,
                    variant=(args.unique or args.attraction_weight != 1.0 or args.features != "pixels"),
                    selected_unique_indices=int(len(np.unique(ids))),
                    note="Generator architecture and checkpoint are unchanged")
    (out_dir / "selection.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    print(f"Saved {len(ids)} PNGs in {out_dir} (unique candidate indices: {len(set(ids.tolist()))})")


if __name__ == "__main__":
    main()
